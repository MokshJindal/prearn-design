export type DocumentType = 'pitch-deck' | 'brochure' | 'one-pager' | 'flyer';

export type AspectRatio = '16:9' | '4:3' | 'a4-portrait' | 'a4-landscape' | 'trifold';

export interface ThemeColors {
  id: string;
  name: string;
  category: 'dark' | 'light' | 'vibrant';
  bg: string;
  surface: string;
  surfaceBorder: string;
  primary: string;
  primaryHover: string;
  accent: string;
  textPrimary: string;
  textSecondary: string;
  textMuted: string;
  cardBg: string;
  badgeBg: string;
  badgeText: string;
}

export interface DesignElement {
  id: string;
  type: 
    | 'heading' 
    | 'subheading' 
    | 'paragraph' 
    | 'badge' 
    | 'stat-block' 
    | 'feature-card' 
    | 'bullet-list' 
    | 'comparison-table' 
    | 'team-card' 
    | 'quote' 
    | 'cta-button'
    | 'custom-html';
  content?: string;
  title?: string;
  subtitle?: string;
  tag?: string;
  statValue?: string;
  statLabel?: string;
  statChange?: string;
  items?: string[];
  columns?: string[];
  rows?: { cells: string[] }[];
  author?: string;
  role?: string;
  avatar?: string;
  style?: {
    fontSize?: string;
    fontWeight?: string;
    color?: string;
    backgroundColor?: string;
    borderColor?: string;
    textAlign?: 'left' | 'center' | 'right';
    padding?: string;
    borderRadius?: string;
  };
  gridSpan?: string; // e.g. "col-span-12 md:col-span-6"
}

export interface SlidePage {
  id: string;
  title: string;
  category?: 'title' | 'problem' | 'solution' | 'market' | 'product' | 'traction' | 'business-model' | 'competition' | 'team' | 'financials' | 'closing' | 'content';
  layout: 'hero' | 'two-column' | 'three-column' | 'bento-grid' | 'split-stat' | 'timeline' | 'table' | 'quote' | 'custom';
  badge?: string;
  headline: string;
  subheadline?: string;
  description?: string;
  elements: DesignElement[];
  html?: string; // Bespoke ultra-premium visual code generated by Claude (Tailwind + SVG)
  customStyles?: {
    backgroundColor?: string;
    backgroundGradient?: string;
  };
  notes?: string;
}

export interface DesignDocument {
  id: string;
  title: string;
  subtitle?: string;
  type: DocumentType;
  aspectRatio: AspectRatio;
  themeId: string;
  fontFamily: 'sans' | 'serif' | 'display' | 'mono';
  slides: SlidePage[];
  createdAt: string;
  updatedAt: string;
}

export interface ChatMessage {
  id: string;
  role: 'user' | 'assistant' | 'system';
  content: string;
  timestamp: string;
  isStreaming?: boolean;
  generatedSlide?: SlidePage;
}
